public class Datatype {
	public static void main (String[] args){
		byte age = 80;
		short quantity= 10000;
		int population =27388373;
		long worldsPopulation= 32;
		//byte method
		System.out.printf("President Tinubu is %d years old%n", age);
		//short method (putting a comma in between the percentage helps the number to be seperated so we understand)
		System.out.printf ("I ordered %,d quantity of phones in 2026%n",quantity);
		//int method (INTEGER)
		System.out.printf ("The population of Nigeria is %,d%n ",population);
		System.out.printf ("The worlds population is summarised to", worldsPopulation);
	}
}